#!/bin/bash
# Swap the home-screen app icon (Android launcher + iOS) for the next build:
#   tool/app_icon.sh diwali     # everyday logo with a mango-leaf and marigold thoranam
#   tool/app_icon.sh pongal     # … with an aavaram poo thoranam
#   tool/app_icon.sh christmas  # … with a pine garland and baubles
#   tool/app_icon.sh valentine  # … with a rose garland and little hearts
#   tool/app_icon.sh puthandu   # … with mango leaves, malli, kanakambaram and konrai
#   tool/app_icon.sh eid       # … with little lanterns, stars and crescents on a gold chain
#   tool/app_icon.sh national  # … with tricolour bunting and rosettes
#   tool/app_icon.sh vinayagar # … with erukkam poo, marigolds and arugampul
#   tool/app_icon.sh navaratri # … with silk pennants and marigolds
#   tool/app_icon.sh karthigai # … with jasmine, marigolds and lit hanging lamps
#   tool/app_icon.sh standard   # everyday icon
# Phones get the new icon with the next app update (Android only changes an icon in place
# through an update; swapping it from inside the app removes it from many home screens).
# Sets live in branding/app_icon/, generated by design/festival-art/festive_logo.py.
set -euo pipefail
cd "$(dirname "$0")/.."
name="${1:-}"
src="branding/app_icon/$name"
if [ -z "$name" ] || [ ! -d "$src" ]; then
  echo "usage: tool/app_icon.sh standard|diwali|pongal|christmas|valentine|puthandu|eid|national|vinayagar|navaratri|karthigai" >&2
  exit 1
fi
for d in mdpi hdpi xhdpi xxhdpi xxxhdpi; do
  cp "$src/android/mipmap-$d/"*.png "android/app/src/main/res/mipmap-$d/"
done
cp "$src/ios/AppIcon.appiconset/"* ios/Runner/Assets.xcassets/AppIcon.appiconset/
echo "App icon set to '$name' — build and publish an update for it to reach phones."
